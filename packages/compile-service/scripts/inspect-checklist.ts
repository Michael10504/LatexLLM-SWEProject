/**
 * Step 14: start a sandbox container exactly as the app does and prove every limit from
 * `docker inspect` plus in-container probes. Writes docs/step14-inspect-checklist.md.
 *   npm run checklist
 */
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { checklistMarkdown, checkRunningContainer } from '../src/sandbox/inspectChecklist';
import { runDocker } from '../src/sandbox/runDocker';
import { SandboxRunner } from '../src/sandbox/SandboxRunner';
import { DEFAULT_SANDBOX_CONFIG } from '../src/types';

const runner = new SandboxRunner(undefined, { logger: { warn: console.warn, debug: () => {} } });
const ID = 'checklist';

async function main(): Promise<number> {
  const name = await runner.ensureRunning(ID, path.resolve(__dirname, '../fixtures/basic'));
  const items = await checkRunningContainer(runner, name);
  for (const i of items) console.log(`${i.pass ? 'PASS' : 'FAIL'}  ${i.label.padEnd(40)} expected ${i.expected}, got ${i.actual}`);
  const failed = items.filter((i) => !i.pass).length;
  const docker = (await runDocker(DEFAULT_SANDBOX_CONFIG, ['version', '--format', '{{.Server.Version}}'])).stdout.toString().trim();
  const md = [
    '# WS-3 Step 14: Sandbox inspect checklist',
    '',
    `- **Date:** ${new Date().toISOString().slice(0, 10)}`,
    `- **Machine:** ${os.type()} ${os.release()}, ${os.cpus()[0]?.model ?? 'unknown CPU'} (${os.cpus().length} threads), ${Math.round(os.totalmem() / 1024 ** 3)} GB RAM`,
    `- **Docker Engine:** ${docker}`,
    `- **Container:** \`${name}\` started by \`SandboxRunner.ensureRunning\` (the fixed command)`,
    `- **Result:** ${items.length - failed}/${items.length} checks passed`,
    '',
    checklistMarkdown(items),
    '',
    'Generated by `npm run checklist` (`scripts/inspect-checklist.ts`).',
    '',
  ].join('\n');
  const out = path.resolve(__dirname, '../docs/step14-inspect-checklist.md');
  fs.writeFileSync(out, md);
  console.log(`\n${failed === 0 ? 'ALL CHECKS PASSED' : `${failed} CHECK(S) FAILED`}  (written to ${out})`);
  await runner.stop(ID);
  return failed ? 1 : 0;
}

main().then(
  (code) => process.exit(code),
  (e) => {
    console.error('Checklist crashed:', e);
    process.exit(1);
  },
);
